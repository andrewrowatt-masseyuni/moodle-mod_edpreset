$capabilities = [

    // This module is never actually added to a course. The capability exists because
    // course_allowed_module() (course/lib.php) checks mod/<name>:addinstance, and that is
    // what gates whether the presets appear in a given course for a given role.
    'mod/edpreset:addinstance' => [
        'riskbitmask' => RISK_XSS,

        'captype' => 'write',
        'contextlevel' => CONTEXT_COURSE,
        'archetypes' => [
            'editingteacher' => CAP_ALLOW,
            'manager' => CAP_ALLOW,
        ],
        'clonepermissionsfrom' => 'moodle/course:manageactivities',
    ],

    // Lets a user see and add presets whose curator has marked them "Ready for review", alongside
    // the released ones everyone sees. Checked in the target course's context, so it can be granted
    // through a site-wide role or through a role in particular courses.
    'mod/edpreset:reviewpresets' => [
        'captype' => 'read',
        'contextlevel' => CONTEXT_COURSE,
        'archetypes' => [
            'manager' => CAP_ALLOW,
        ],
    ],
];
